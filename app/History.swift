// History, on this Mac only (the user, 2026-10-19): every voice take (text + its recording) and every text copied to
// the clipboard, so nothing is wiped and anything can be picked up again from the menu bar. Recordings are kept
// 14 days (as Voice Notes did). Items from password managers (concealed or transient pasteboard types) are never kept,
// nor Drafter's own pastes (marked with its own pasteboard type). Since 14 November 2026 (Quick panel) the clipboard
// history is trimmed to `quickMax` rows / `quickDays` days, skips `quickSecret` matches, keeps an image's size only,
// and rows can be removed (`forget`).
import AppKit
import Carbon
import ImageIO
import PDFKit

enum History {
    static let takesFile = Home.data.appendingPathComponent("takes.jsonl")
    static let clipFile = Home.data.appendingPathComponent("clipboard.jsonl")
    static let audioDir = Home.data.appendingPathComponent("audio")
    static let ownType = NSPasteboard.PasteboardType((Bundle.main.bundleIdentifier ?? "drafter") + ".own")
    private static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                                 "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", ownType.rawValue]
    private static var lastChange = NSPasteboard.general.changeCount
    private static let queue = DispatchQueue(label: "drafter.history")

    private static func append(_ url: URL, _ obj: [String: Any]) {
        guard let d = try? JSONSerialization.data(withJSONObject: obj), var line = String(data: d, encoding: .utf8) else { return }
        line += "\n"
        if let h = try? FileHandle(forWritingTo: url) { h.seekToEndOfFile(); h.write(line.data(using: .utf8)!); try? h.close() }
        else { try? line.write(to: url, atomically: true, encoding: .utf8) }
    }

    static func read(_ url: URL, last n: Int) -> [[String: Any]] {
        guard let s = (n <= 20 ? tail(url, bytes: 512_000) : nil) ?? (try? String(contentsOf: url, encoding: .utf8)) else { return [] }
        let rows = s.split(separator: "\n").suffix(n).reversed().compactMap { try? JSONSerialization.jsonObject(with: Data($0.utf8)) as? [String: Any] }
        // rows listed in data/drafts-hidden.json (scripts/hide_bad_drafts.py) are not listed; the files stay as they are
        guard url == typedFile || url == draftsFile else { return rows }
        return DraftHide.drop(rows, kind: url == draftsFile ? "draft" : "sent", hidden: DraftHide.load(hiddenFile))
    }

    /// The file's last `bytes`, from the start of a line (a row is at most ~20 KB): a look at the last row never
    /// reads the whole file (Argon 24: every clipboard change read all of clipboard.jsonl). nil: read it whole.
    static func tail(_ url: URL, bytes: Int) -> String? {
        guard let h = try? FileHandle(forReadingFrom: url) else { return nil }
        defer { try? h.close() }
        guard let size = try? h.seekToEnd(), size > UInt64(bytes) else { return nil }
        try? h.seek(toOffset: size - UInt64(bytes))
        guard var d = try? h.readToEnd() else { return nil }
        while let b = d.first, b & 0xC0 == 0x80 { d.removeFirst() }   // started inside a letter
        guard let s = String(data: d, encoding: .utf8), let nl = s.firstIndex(of: "\n") else { return nil }
        return String(s[s.index(after: nl)...])
    }

    // MARK: takes

    /// A take (or an Enter piece): its text and its sound, kept. `raw` is what the reader heard before clean-up and
    /// the spoken rules, kept in data/takes.jsonl when it differs, so words a rule cut are never lost.
    /// Where the last take's recording went (a long note links to it).
    static var lastAudio = ""

    static func take(_ text: String, audio: [Float], app: String, loud: Bool, raw: String = "", outcome: String = "") {
        let id = UUID().uuidString, secs = Double(audio.count) / 16000
        if !audio.isEmpty { lastAudio = audioDir.appendingPathComponent(id + ".wav").path }
        queue.async {
            try? FileManager.default.createDirectory(at: audioDir, withIntermediateDirectories: true)
            let wav = audioDir.appendingPathComponent(id + ".wav")
            if !audio.isEmpty { writeWav(audio, to: wav) }
            var row: [String: Any] = ["id": id, "t": Date().timeIntervalSince1970, "text": text, "secs": (secs * 10).rounded() / 10,
                                      "app": app, "loud": loud, "audio": audio.isEmpty ? "" : wav.path]
            if !raw.isEmpty, raw != text { row["raw"] = raw }
            if !outcome.isEmpty { row["outcome"] = outcome }
            append(takesFile, row)
        }
    }

    static func writeWav(_ s: [Float], to url: URL) {
        var d = Data()
        func u32(_ v: UInt32) { var x = v.littleEndian; d.append(Data(bytes: &x, count: 4)) }
        func u16(_ v: UInt16) { var x = v.littleEndian; d.append(Data(bytes: &x, count: 2)) }
        let bytes = UInt32(s.count * 2)
        d.append("RIFF".data(using: .ascii)!); u32(36 + bytes); d.append("WAVEfmt ".data(using: .ascii)!)
        u32(16); u16(1); u16(1); u32(16000); u32(32000); u16(2); u16(16)
        d.append("data".data(using: .ascii)!); u32(bytes)
        var pcm = s.map { Int16(max(-1, min(1, $0)) * 32767).littleEndian }
        d.append(Data(bytes: &pcm, count: pcm.count * 2))
        try? d.write(to: url)
    }

    /// Recordings older than 14 days go; their text stays in takes.jsonl.
    static func prune() {
        compactClipboard()
        queue.async {
            let old = Date().addingTimeInterval(-14 * 86400)
            for f in (try? FileManager.default.contentsOfDirectory(at: audioDir, includingPropertiesForKeys: [.contentModificationDateKey])) ?? [] {
                if let m = (try? f.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate, m < old {
                    try? FileManager.default.removeItem(at: f)
                }
            }
        }
    }

    // MARK: typing

    static let typedFile = Home.data.appendingPathComponent("typed.jsonl")     // lines the user sent (Return), written by the engine
    static let draftsFile = Home.data.appendingPathComponent("drafts.jsonl")   // text the user typed and left without sending

    static let hiddenFile = Home.data.appendingPathComponent("drafts-hidden.json")   // rows the window skips

    /// `t`: the user's last key in this text (DraftCaptureRules.stamps), `started` ("t0"): the user's first key, so the window shows
    /// how long it took; nil keeps the row as before. `replacing`: the t of the row this draft continues
    /// (DraftCaptureRules.record); that row goes, this one is added. `est`: the user's keys did not explain the field's text,
    /// this is the estimate ("est": true; absent on other rows).
    static func draft(_ text: String, app: String, at t: Double = Date().timeIntervalSince1970, started: Double? = nil, est: Bool = false, replacing: Double? = nil) {
        var row: [String: Any] = ["t": t, "text": text, "app": app]
        if let started, started <= t { row["t0"] = started }
        if est { row["est"] = true }
        queue.async {
            if let replacing { drop(draftsFile) { ($0["t"] as? NSNumber)?.doubleValue == replacing } }
            append(draftsFile, row)
        }
    }

    // MARK: clipboard

    /// Called twice a second: a new text on the clipboard is kept (never secrets, never Drafter's own pastes). Skipped:
    /// password managers and anything marked concealed, transient or auto-generated (nspasteboard.org), copies under
    /// secure input, Drafter's own pastes and the clipboard it puts back after one (`skipChange`), and texts matching
    /// a `quickSecret` pattern (API keys, card numbers, one-time codes). An image copy is a row "Image · W × H"; with
    /// `clipTotalMB` on, the picture is kept in data/clips/ in the type it came in. Clip kinds round (17 November 2026):
    /// several files are one row, a PDF keeps its first page as a picture (and PDF data itself), a formatted text keeps
    /// its formatting (data/clips/*.pboard), a text gets its shape (colour, table, code). A repeated copy is written
    /// again; readers keep its newest row (QuickRules).
    static func watchClipboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if skipped.remove(pb.changeCount) != nil { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: skipTypes), !IsSecureEventInputEnabled() else { return }
        let front = NSWorkspace.shared.frontmostApplication
        var row: [String: Any] = ["t": Date().timeIntervalSince1970, "app": front?.localizedName ?? ""]
        var s = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines)
        // clip kinds round (17 November 2026): bytes to keep in data/clips/ beside the row, by file name
        var files: [String: Data] = [:], pdfText: [String: String] = [:]
        let st = Drafter.shared.settings, cap = st.clipImageMB * 1_000_000, keepBytes = st.clipTotalMB > 0
        var kind = ClipRules.kind(types: types, string: s)
        // a colour from a colour picker: no text, an NSColor; kept as its hex value
        if kind == .text, s?.isEmpty ?? true, types.contains(ClipKindRules.colorType),
           let c = (pb.readObjects(forClasses: [NSColor.self]) as? [NSColor])?.first?.usingColorSpace(.sRGB) {
            s = ClipKindRules.hex(.init(r: Double(c.redComponent), g: Double(c.greenComponent), b: Double(c.blueComponent), a: Double(c.alphaComponent)))
            kind = .text
        }
        switch kind {
        case .file:
            let urls = (pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
            guard let first = urls.first else { return }
            let paths = urls.prefix(50).map(\.path)
            row["kind"] = "file"; row["files"] = paths
            // several files: one row, every path on its own line (paste puts them all back)
            row["text"] = paths.count > 1 ? paths.joined(separator: "\n") : first.path
            var total = 0
            for u in urls.prefix(50) {
                let v = try? u.resourceValues(forKeys: [.fileSizeKey, .isDirectoryKey])
                if v?.isDirectory != true, let n = v?.fileSize { total += n }
            }
            if total > 0 { row["bytes"] = total }
            if let shape = ClipKindRules.fileShape(paths) { row["shape"] = shape.rawValue }
            // one PDF: its first page as a picture, kept like a copied picture (the file itself stays where it is)
            if paths.count == 1, ClipKindRules.isPDF(first.path), keepBytes, let t = pdfThumb(url: first), t.png.count <= cap {
                let name = ClipRules.clipName(t.png); row["clip"] = name; row["page"] = [t.w, t.h, t.pages]
                files[name] = t.png; pdfText[name] = t.text
            }
        case .image:
            if let pdf = pb.data(forType: NSPasteboard.PasteboardType("com.adobe.pdf")), ClipKindRules.imageType((pb.types ?? []).map(\.rawValue)) == nil {
                // PDF data (a page copied from Preview, a vector drawing): the PDF kept to paste back, its first page shown
                guard let t = pdfThumb(data: pdf) else { return }
                row["kind"] = "image"; row["shape"] = ClipShape.pdf.rawValue
                row["text"] = t.pages > 1 ? "PDF · \(t.pages) pages" : "PDF · \(t.w) × \(t.h)"; row["image"] = [t.w, t.h]
                if keepBytes, pdf.count <= cap, t.png.count <= cap {
                    let thumb = ClipRules.clipName(t.png), orig = ClipRules.clipName(pdf, ext: "pdf")
                    row["clip"] = thumb; row["data"] = orig; row["bytes"] = pdf.count
                    files[thumb] = t.png; files[orig] = pdf; pdfText[thumb] = t.text
                }
                break
            }
            guard let (w, h, bytes, ext) = imageData(pb, cap: cap) else { return }
            row["kind"] = "image"; row["text"] = ClipRules.imageText(w, h); row["image"] = [w, h]
            if keepBytes, let bytes {
                let name = ClipRules.clipName(bytes, ext: ext)
                row["clip"] = name; row["bytes"] = bytes.count; files[name] = bytes
            }
        case .link, .text:
            guard let s, !s.isEmpty, s.count <= 20000, !QuickRules.isSecret(s, secretRules()) else { return }
            row["text"] = s
            let html = pb.string(forType: .html)
            if ClipRules.link(s) != nil {
                row["kind"] = "link"
                // the title only from what the copy carried (the browser's link name, the anchor's words), else one
                // the user copied before for the same address; nothing is fetched
                var title = pb.string(forType: NSPasteboard.PasteboardType("public.url-name"))?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
                if title.isEmpty || title == s, let html { title = ClipKindRules.anchorTitle(html: html, url: s) ?? "" }
                if title.isEmpty || title == s { title = Quick.shared.knownTitle(s) }
                if !title.isEmpty, title != s { row["title"] = String(title.prefix(300)) }
            } else {
                if ClipRules.rich(types) { row["rich"] = true }
                if let shape = ClipKindRules.textShape(types: types, text: s, html: html) {
                    row["shape"] = shape.rawValue
                    switch shape {
                    case .color: if let c = ClipKindRules.color(s) { row["color"] = ClipKindRules.hex(c) }
                    case .table: if let t = ClipKindRules.table(text: s, html: html) { row["table"] = [t.cols, t.rows] }
                    case .code: row["lang"] = ClipKindRules.language(s) ?? ""
                    default: break
                    }
                }
                // the formatting as copied (RTF, RTFD, HTML), kept beside the row so ↵ pastes it as it was
                if keepBytes, ClipRules.rich(types), let fmt = formatted(pb), fmt.count <= cap {
                    let name = ClipRules.clipName(fmt, ext: "pboard"); row["data"] = name; files[name] = fmt
                }
            }
            Clip.copied(s, from: front?.bundleIdentifier ?? "")
            if Drafter.shared.settings.pickOffer, ClipRules.link(s) == nil { PickPanel.offerAfterCopy(s) }
        }
        let text = row["text"] as? String ?? "", clip = row["clip"] as? String
        if let last = read(clipFile, last: 1).first,
           ClipRules.dedupeKey(text: last["text"] as? String ?? "", clip: last["clip"] as? String) == ClipRules.dedupeKey(text: text, clip: clip) { return }
        Quick.shared.copied(row)
        let texts = pdfText
        queue.async {
            for (name, d) in files.sorted(by: { $0.key < $1.key }) {
                // a PDF's own text beside its page picture, so search finds it (no picture reading needed)
                if let t = texts[name], !t.isEmpty, !FileManager.default.fileExists(atPath: clipURL(name + ".txt").path) {
                    try? FileManager.default.createDirectory(at: clipsDir, withIntermediateDirectories: true)
                    try? t.write(to: clipURL(name + ".txt"), atomically: true, encoding: .utf8)
                }
                if ClipKindRules.type(forName: name) != nil { saveClip(d, name: name) } else { saveData(d, name: name) }
            }
            append(clipFile, row)
            appended += 1
            if appended % 100 == 0 { compactClipboard() }
        }
    }

    // MARK: picked parts (app/PickPanel.swift, 15 November 2026)

    /// A pick kept as its own clip: a text row in clipboard.jsonl like a copy, plus `from` (the source's id),
    /// `picked` (its ranges) and `via` = "pick" (PickRecord.row). The source row is never touched. A clipboard row is
    /// never learned as the user's writing (the corpus uses copies only to leave lines out); `mine` marks a pick from the user's own
    /// draft, take or sent line. `remove`: its Undo, that one row. Read side: `PickRecord.read(row)`.
    static func keepPick(_ rec: PickRecord, app: String, remove: Bool = false, file: URL = clipFile) {
        let row = rec.row(app: app)
        if !remove, file == clipFile { Quick.shared.copied(row) }
        queue.async {
            if remove { drop(file) { PickRules.isRow($0, of: rec) } } else { PickRules.append(file, row) }
            if remove, file == clipFile { DispatchQueue.main.async { Quick.shared.refresh() } }
        }
    }

    // MARK: copied pictures (data/clips/)

    /// A captured picture (app/Capture.swift) as an image row, like a copied one: stored, read once, on the tape.
    @discardableResult
    /// `shot`: the shot pack's id (data/shots/<id>/, app/ShotStore.swift), so the journal finds its note and marks.
    static func addPicture(_ png: Data, width w: Int, height h: Int, app: String, shot: String? = nil) -> [String: Any] {
        let name = ClipRules.clipName(png)
        var row: [String: Any] = ["t": Date().timeIntervalSince1970, "app": app, "kind": "image", "text": ClipRules.imageText(w, h),
                                  "image": [w, h], "via": "capture"]
        if let shot { row["shot"] = shot }
        let keep = Drafter.shared.settings.clipTotalMB > 0
        if keep { row["clip"] = name; row["bytes"] = png.count }
        Quick.shared.copied(row)
        queue.async {
            if keep { saveClip(png, name: name) }
            append(clipFile, row)
        }
        return row
    }

    static let clipsDir = Home.data.appendingPathComponent("clips")
    static func clipURL(_ name: String) -> URL { clipsDir.appendingPathComponent(name) }
    /// The picture's read text, beside it ("" until Vision read it).
    static func clipText(_ name: String) -> String { (try? String(contentsOf: clipURL(name + ".txt"), encoding: .utf8)) ?? "" }

    /// On the history queue: the picture once, then its text read on this Mac (once; a utility queue), then the
    /// Quick panel re-reads.
    static func saveClip(_ png: Data, name: String) {
        try? FileManager.default.createDirectory(at: clipsDir, withIntermediateDirectories: true)
        let u = clipURL(name)
        if !FileManager.default.fileExists(atPath: u.path) { try? png.write(to: u, options: .atomic) }
        readClip(name)
    }
    /// A kept copy that is not a picture (formatting, a PDF): written once, nothing read from it.
    static func saveData(_ d: Data, name: String) {
        try? FileManager.default.createDirectory(at: clipsDir, withIntermediateDirectories: true)
        let u = clipURL(name)
        if !FileManager.default.fileExists(atPath: u.path) { try? d.write(to: u, options: .atomic) }
    }
    static func readClip(_ name: String) {
        let txt = clipURL(name + ".txt")
        let fm = FileManager.default
        guard !fm.fileExists(atPath: txt.path) || !fm.fileExists(atPath: lookURL(name).path) else { return }
        DispatchQueue.global(qos: .utility).async {
            guard let src = CGImageSourceCreateWithURL(clipURL(name) as CFURL, nil),
                  let img = CGImageSourceCreateImageAtIndex(src, 0, nil) else { return }
            let t0 = Date()
            if !fm.fileExists(atPath: txt.path) {
                let text = Screen.read(img)
                try? text.write(to: txt, atomically: true, encoding: .utf8)
                log("clips: read a picture, \(text.count) chars in \(Int(Date().timeIntervalSince(t0) * 1000)) ms")
            }
            lookClip(name, img)
            DispatchQueue.main.async { Quick.shared.refresh() }
        }
    }

    // MARK: what a picture is (pictures round, 24 November 2026, app/PictureLookRules.swift)

    /// Vision's labels for a picture, beside it (data/clips/<name>.look); made once, on this Mac.
    static func lookURL(_ name: String) -> URL { clipURL(name + ".look") }
    static func lookClip(_ name: String, _ img: CGImage) {
        let labels = PictureLook.labels(img)
        try? PictureLookRules.sidecar(labels: labels).write(to: lookURL(name), atomically: true, encoding: .utf8)
    }
    /// The labels, nil until Vision named it.
    static func clipLabels(_ name: String) -> [String]? {
        (try? String(contentsOf: lookURL(name), encoding: .utf8)).flatMap { PictureLookRules.labels(sidecar: $0) }
    }
    /// Pictures kept before this round: named once, one at a time on a background queue, a while after launch.
    static func lookMissing() {
        DispatchQueue.global(qos: .background).asyncAfter(deadline: .now() + 20) {
            let fm = FileManager.default
            guard let names = try? fm.contentsOfDirectory(atPath: clipsDir.path) else { return }
            var n = 0
            let t0 = Date()
            for name in names where ClipKindRules.type(forName: name) != nil && clipLabels(name) == nil {
                autoreleasepool {
                    guard let src = CGImageSourceCreateWithURL(clipURL(name) as CFURL, nil),
                          let img = CGImageSourceCreateImageAtIndex(src, 0, nil) else { return }
                    lookClip(name, img); n += 1
                }
            }
            if n > 0 {
                log("clips: named \(n) pictures in \(Int(Date().timeIntervalSince(t0) * 1000)) ms")
                DispatchQueue.main.async { Quick.shared.refresh(); AppWindow.shared.model.reload() }
            }
        }
    }

    /// Pictures no row points at, then the oldest over `clipTotalMB` (on the history queue, after a trim or a removal).
    static func pruneClips(live: Set<String>) {
        let fm = FileManager.default
        guard let names = try? fm.contentsOfDirectory(atPath: clipsDir.path) else { return }
        let files: [ClipRules.Stored] = names.filter { !$0.hasSuffix(".txt") && !$0.hasSuffix(".look") }.map { n in
            let a = try? fm.attributesOfItem(atPath: clipURL(n).path)
            return .init(name: n, bytes: (a?[.size] as? Int) ?? 0, t: (a?[.modificationDate] as? Date)?.timeIntervalSince1970 ?? 0)
        }
        let gone = ClipRules.prune(files, live: live, total: Drafter.shared.settings.clipTotalMB * 1_000_000)
        for n in gone { try? fm.removeItem(at: clipURL(n)); try? fm.removeItem(at: clipURL(n + ".txt")); try? fm.removeItem(at: lookURL(n)) }
        for n in names where n.hasSuffix(".txt") && !names.contains(String(n.dropLast(4))) { try? fm.removeItem(at: clipURL(n)) }
        for n in names where n.hasSuffix(".look") && !names.contains(String(n.dropLast(5))) { try? fm.removeItem(at: clipURL(n)) }
        if !gone.isEmpty { log("clips: removed \(gone.count) pictures") }
    }
    /// Every stored file a row points at: its picture and its kept copy ("data": formatting, PDF).
    private static func liveClips() -> Set<String> {
        Set(read(clipFile, last: 100_000).flatMap { [$0["clip"] as? String, $0["data"] as? String].compactMap { $0 } })
    }

    /// Width, height, the picture's bytes in the type it came in (PNG, JPEG, TIFF, HEIC, GIF, WebP: never all made
    /// PNG; clip kinds round, 17 November 2026) and its file extension. Over `cap` it is kept as PNG when that fits
    /// (a large TIFF), else nil bytes: then only the size is kept, as before round three.
    private static func imageData(_ pb: NSPasteboard, cap: Int) -> (Int, Int, Data?, String)? {
        guard let (w, h) = imageSize(pb) else { return nil }
        guard let t = ClipKindRules.imageType((pb.types ?? []).map(\.rawValue)), let d = pb.data(forType: NSPasteboard.PasteboardType(t)) else { return (w, h, nil, "png") }
        if d.count <= cap { return (w, h, d, ClipKindRules.ext(forType: t)) }
        if t != "public.png", let rep = NSBitmapImageRep(data: d), let png = rep.representation(using: .png, properties: [:]), png.count <= cap {
            return (w, h, png, "png")
        }
        return (w, h, nil, "png")
    }

    /// The copy's formatting, every rich type it carried (RTFD, RTF, HTML, and the plain text) in one property list.
    private static func formatted(_ pb: NSPasteboard) -> Data? {
        var d: [String: Data] = [:]
        for t in ["com.apple.flat-rtfd", "public.rtf", "public.html", "public.utf8-plain-text"] {
            if let v = pb.data(forType: NSPasteboard.PasteboardType(t)) { d[t] = v }
        }
        guard d.keys.contains(where: { ClipRules.richTypes.contains($0) }) else { return nil }
        return try? PropertyListSerialization.data(fromPropertyList: d, format: .binary, options: 0)
    }
    /// A kept formatted copy back as its pasteboard types (nil: gone or unreadable).
    static func formattedTypes(_ name: String) -> [String: Data]? {
        guard let d = try? Data(contentsOf: clipURL(name)) else { return nil }
        return (try? PropertyListSerialization.propertyList(from: d, options: [], format: nil)) as? [String: Data]
    }

    /// A PDF's first page drawn as a picture (longest side 900 px), its page size in points, its page count and up to
    /// 4,000 characters of its text (for search). Read on this Mac only.
    static func pdfThumb(url: URL) -> (png: Data, w: Int, h: Int, pages: Int, text: String)? {
        guard let doc = CGPDFDocument(url as CFURL) else { return nil }
        return pdfThumb(doc, text: firstText(PDFDocument(url: url)))
    }
    static func pdfThumb(data: Data) -> (png: Data, w: Int, h: Int, pages: Int, text: String)? {
        guard let p = CGDataProvider(data: data as CFData), let doc = CGPDFDocument(p) else { return nil }
        return pdfThumb(doc, text: firstText(PDFDocument(data: data)))
    }
    /// The text of the first 3 pages only (a long PDF is never read whole while copying).
    private static func firstText(_ d: PDFDocument?) -> String {
        guard let d else { return "" }
        return (0..<min(3, d.pageCount)).compactMap { d.page(at: $0)?.string }.joined(separator: "\n")
    }
    private static func pdfThumb(_ doc: CGPDFDocument, text: String?) -> (png: Data, w: Int, h: Int, pages: Int, text: String)? {
        guard !doc.isEncrypted || doc.isUnlocked, let page = doc.page(at: 1) else { return nil }
        let box = page.getBoxRect(.cropBox)
        guard box.width > 1, box.height > 1 else { return nil }
        let s = 900 / max(box.width, box.height)
        let pw = Int((box.width * s).rounded()), ph = Int((box.height * s).rounded())
        guard let ctx = CGContext(data: nil, width: pw, height: ph, bitsPerComponent: 8, bytesPerRow: 0, space: CGColorSpace(name: CGColorSpace.sRGB)!,
                                  bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return nil }
        ctx.setFillColor(CGColor(red: 1, green: 1, blue: 1, alpha: 1)); ctx.fill(CGRect(x: 0, y: 0, width: pw, height: ph))
        ctx.scaleBy(x: s, y: s); ctx.translateBy(x: -box.minX, y: -box.minY)
        ctx.drawPDFPage(page)
        guard let img = ctx.makeImage(), let png = NSBitmapImageRep(cgImage: img).representation(using: .png, properties: [:]) else { return nil }
        return (png, Int(box.width.rounded()), Int(box.height.rounded()), doc.numberOfPages, String((text ?? "").prefix(4000)))
    }

    /// The pixel size of an image on the clipboard, read from its header (nothing is decoded or kept).
    private static func imageSize(_ pb: NSPasteboard) -> (Int, Int)? {
        for t in [NSPasteboard.PasteboardType.png, .tiff] + ["public.jpeg", "public.heic", "com.compuserve.gif", "org.webmproject.webp"].map { NSPasteboard.PasteboardType($0) } {
            guard let d = pb.data(forType: t), let src = CGImageSourceCreateWithData(d as CFData, nil),
                  let p = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
                  let w = p[kCGImagePropertyPixelWidth] as? Int, let h = p[kCGImagePropertyPixelHeight] as? Int else { continue }
            return (w, h)
        }
        return nil
    }

    /// A clipboard change Drafter made itself (the clipboard it puts back after a paste): not kept as a new copy.
    private static var skipped = Set<Int>()
    static func skipChange(_ count: Int) { if skipped.count > 20 { skipped.removeAll() }; skipped.insert(count) }

    private static var appended = 0
    private static var rulesFor: [String] = [], rules: [NSRegularExpression] = []
    static func secretRules() -> [NSRegularExpression] {
        let p = Drafter.shared.settings.quickSecret
        if p != rulesFor { rulesFor = p; rules = QuickRules.secretRules(p) }
        return rules
    }

    /// clipboard.jsonl trimmed (on the history queue): the newest row of each text, at most `quickMax` rows, none
    /// older than `quickDays`, none that match `quickSecret`. At start (prune) and every 100 copies.
    static func compactClipboard() {
        let st = Drafter.shared.settings
        let max = st.quickMax, days = st.quickDays, rx = QuickRules.secretRules(st.quickSecret)
        queue.async {
            guard let s = try? String(contentsOf: clipFile, encoding: .utf8) else { return }
            let lines = s.split(separator: "\n", omittingEmptySubsequences: true)
            let rows: [(t: Double, text: String)] = lines.map { l in
                let j = (try? JSONSerialization.jsonObject(with: Data(l.utf8))) as? [String: Any]
                return (j?["t"] as? Double ?? 0, ClipRules.dedupeKey(text: j?["text"] as? String ?? "", clip: j?["clip"] as? String))
            }
            let keep = QuickRules.keepClips(rows, now: Date().timeIntervalSince1970, max: max, days: days) { QuickRules.isSecret($0, rx) }
            if keep.count < lines.count {
                rewrite(clipFile, keep.map { String(lines[$0]) })
                log("clipboard: kept \(keep.count) of \(lines.count) rows")
            }
            pruneClips(live: liveClips())   // the pictures go with their rows
        }
    }

    /// Rows removed from history (Quick panel ⌘⌫, after its undo line is gone): every row of that kind with that text;
    /// a voice take's recording too. typed.jsonl is written by the engine: the rewrite starts over if it grew meanwhile.
    static func forget(_ kind: QuickKind, _ text: String, drafts: [String] = [], picture: String = "") {
        queue.async {
            switch kind {
            case .copied:
                var kept = false
                drop(clipFile) { r in
                    let hit = r["text"] as? String == text && (r["clip"] as? String ?? "") == picture
                    if hit, r["data"] != nil { kept = true }
                    return hit
                }
                if !picture.isEmpty || kept { pruneClips(live: liveClips()) }
            case .voice:
                drop(takesFile) { r in
                    guard r["text"] as? String == text else { return false }
                    if let a = r["audio"] as? String, !a.isEmpty, a.hasPrefix(audioDir.path) { try? FileManager.default.removeItem(atPath: a) }
                    return true
                }
            case .typed:
                let all = Set([text] + drafts)
                drop(typedFile) { all.contains($0["text"] as? String ?? "\u{0}") }
                drop(draftsFile) { all.contains($0["text"] as? String ?? "\u{0}") }
            }
        }
    }

    /// The file without the rows `gone` picks; other lines are kept byte for byte.
    private static func drop(_ url: URL, _ gone: ([String: Any]) -> Bool) {
        for _ in 0..<3 {
            guard let d = try? Data(contentsOf: url), let s = String(data: d, encoding: .utf8) else { return }
            let lines = s.split(separator: "\n", omittingEmptySubsequences: true).map(String.init)
            let kept = lines.filter { l in
                guard let j = (try? JSONSerialization.jsonObject(with: Data(l.utf8))) as? [String: Any] else { return true }
                return !gone(j)
            }
            guard kept.count < lines.count else { return }
            if rewrite(url, kept, ifSize: d.count) { log("history: \(lines.count - kept.count) rows removed from \(url.lastPathComponent)"); return }
        }
    }

    /// Writes `lines` over the file through a temporary file. `ifSize`: only when the file still has that size (an
    /// append by another process since it was read starts the caller over). -> written.
    @discardableResult
    private static func rewrite(_ url: URL, _ lines: [String], ifSize: Int? = nil) -> Bool {
        let tmp = url.deletingLastPathComponent().appendingPathComponent("." + url.lastPathComponent + ".tmp")
        guard (try? (lines.joined(separator: "\n") + (lines.isEmpty ? "" : "\n")).write(to: tmp, atomically: false, encoding: .utf8)) != nil else { return false }
        if let ifSize, ((try? FileManager.default.attributesOfItem(atPath: url.path))?[.size] as? Int) != ifSize {
            try? FileManager.default.removeItem(at: tmp); return false
        }
        return (try? FileManager.default.replaceItemAt(url, withItemAt: tmp)) != nil
    }

    /// Puts a kept text back on the clipboard (marked as Drafter's own, so it is not kept twice).
    static func copy(_ text: String, write: ((NSPasteboard) -> Void)? = nil) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let write { write(pb) } else { pb.setString(text, forType: .string) }
        pb.setString("1", forType: ownType)
        lastChange = pb.changeCount
    }

    // MARK: menu

    static func menu(title: String, file: URL, n: Int) -> NSMenuItem {
        let item = NSMenuItem(title: title, action: nil, keyEquivalent: "")
        let sub = NSMenu()
        let f = DateFormatter(); f.dateFormat = "HH:mm"
        let rows = read(file, last: n)
        if rows.isEmpty { sub.addItem(withTitle: "Nothing yet", action: nil, keyEquivalent: "").isEnabled = false }
        for r in rows {
            guard let text = r["text"] as? String else { continue }
            let when = f.string(from: Date(timeIntervalSince1970: r["t"] as? Double ?? 0))
            let one = text.replacingOccurrences(of: "\n", with: " ")
            let i = NSMenuItem(title: "\(when)  " + (one.count > 60 ? String(one.prefix(57)) + "…" : one),
                               action: #selector(Picker.pick(_:)), keyEquivalent: "")
            i.target = Picker.shared; i.representedObject = text; i.toolTip = String(text.prefix(600))
            sub.addItem(i)
        }
        item.submenu = sub
        return item
    }
}

