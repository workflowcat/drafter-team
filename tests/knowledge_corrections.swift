import Foundation
// swiftc -parse-as-library app/CorrectionRules.swift tests/knowledge_corrections.swift -o app/build/knowledge_corrections-test && app/build/knowledge_corrections-test
@main struct Checks {
    static func main() {
        precondition(CorrectionRules.candidate("tomorow", counts: ["tomorrow": 6]) == "tomorrow")
        precondition(CorrectionRules.candidate("tomorow", counts: ["tomorrow": 4]) == nil)
        precondition(CorrectionRules.candidate("sned", counts: ["send": 15, "shed": 5]) == "send")
        precondition(CorrectionRules.candidate("sned", counts: ["send": 14, "shed": 5]) == nil)
        precondition(CorrectionRules.candidate("Sned", counts: ["send": 15]) == nil)
        precondition(CorrectionRules.candidate("sn3d", counts: ["send": 15]) == nil)
        precondition(CorrectionRules.candidate("поговорти", counts: ["поговорити": 10]) == "поговорити")
        precondition(CorrectionRules.distance("receive", "recieve") == 1)
        precondition(CorrectionRules.candidate("wnat", counts: ["what": 300, "want": 50]) == "what")
        precondition(CorrectionRules.candidate("recieve", counts: ["receive": 5, "recipe": 300]) == "receive")
        precondition(CorrectionRules.candidate("tmp", counts: ["the": 300]) == nil)
        precondition(CorrectionRules.candidate("mvp", counts: ["map": 300]) == nil)
        precondition(CorrectionRules.candidate("teh", counts: ["the": 30]) == "the")
        precondition(CorrectionRules.candidate("xxnd", counts: ["and": 300]) == nil)
        precondition(CorrectionRules.candidate("abndd", counts: ["and": 300]) == nil)
        precondition(CorrectionRules.candidate("thhxx", counts: ["the": 300]) == nil)
        precondition(CorrectionRules.candidate("dont", counts: ["don't": 5, "done": 300]) == "don't")
        precondition(CorrectionRules.candidate("cant", counts: ["can't": 5, "cart": 300]) == "can't")
        precondition(CorrectionRules.candidate("recxxve", counts: ["receive": 10]) == "receive")
        precondition(CorrectionRules.candidate("поговорти", counts: ["поговорити": 10], ukrainian: true) == "поговорити")
        precondition(CorrectionRules.candidate("поговрти", counts: ["поговорити": 10], ukrainian: true) == nil)
        precondition(CorrectionRules.candidate("sned", index: CorrectionRules.Index(["send": 15])) == "send")
        precondition(CorrectionRules.spacing("any way", "anyway", word: { $0 == "anyway" }))
        precondition(CorrectionRules.spacing("anyway", "any way", word: { $0 == "anyway" }))
        precondition(!CorrectionRules.spacing("any qzx", "anyqzx", word: { $0 == "anyway" }))
        precondition(!CorrectionRules.spacing("Hanna", "Hannah", word: { _ in true }))
        var counts = CorrectionRules.counts(legacy: "tomorow\ntomorow\nretun\n", saved: ["retun": 2])
        precondition(counts["tomorow"] == 1)
        precondition(CorrectionRules.kept(counts) == ["retun"])
        CorrectionRules.takeBack("tomorow ", counts: &counts)
        precondition(CorrectionRules.kept(counts) == ["retun", "tomorow"])
        CorrectionRules.takeBack("fresh ", counts: &counts)
        precondition(!CorrectionRules.kept(counts).contains("fresh"))
        CorrectionRules.takeBack("fresh ", counts: &counts)
        precondition(CorrectionRules.kept(counts).contains("fresh"))
        let reload = CorrectionRules.counts(legacy: "tomorow\nretun\n", saved: counts)
        precondition(reload == counts)
        print("PASS: correction ranking and take-back counts")
    }
}
